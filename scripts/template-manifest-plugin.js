import fs from "node:fs";
import path from "node:path";

const TEMPLATES_DIR = "public/Templates";
const OUTPUT_FILE = "src/data/templates.gen.js";

const DOCUMENT_EXTENSIONS = new Set([".docx", ".doc"]);

const ICON_HINTS = [
  ["affidavit", "FileText"],
  ["agreement", "FileSignature"],
  ["license", "Home"],
  ["kiraya", "Home"],
  ["leave", "Home"],
  ["sale", "Landmark"],
  ["vikrit", "Landmark"],
  ["release", "Unlock"],
  ["hakka", "Unlock"],
  ["power", "Shield"],
  ["poa", "Shield"],
  ["mukhtyar", "Shield"],
  ["other", "FolderOpen"],
];

function humanize(name) {
  const base = name.replace(/\.(docx|doc)$/i, "");
  return base
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function pickIcon(folderName) {
  const lower = folderName.toLowerCase();
  for (const [hint, icon] of ICON_HINTS) {
    if (lower.includes(hint)) return icon;
  }
  return "FolderOpen";
}

function scanDirectory(dir) {
  let entries = [];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return { files: [], categories: [] };
  }

  const folders = entries.filter((e) => e.isDirectory());
  const files = entries
    .filter((e) => e.isFile())
    .filter((e) => DOCUMENT_EXTENSIONS.has(path.extname(e.name).toLowerCase()))
    .map((f) => {
      const rel = path.join(dir, f.name).replace(/\\/g, "/");
      const publicPath = rel.replace(/^public\//, "");
      const unsupported = path.extname(f.name).toLowerCase() === ".doc";
      return {
        name: humanize(f.name),
        path: publicPath,
        unsupported,
      };
    });

  const categories = folders
    .map((folder) => {
      const nested = scanDirectory(path.join(dir, folder.name));
      if (nested.files.length === 0 && nested.categories.length === 0) {
        return null;
      }
      return {
        name: humanize(folder.name),
        icon: pickIcon(folder.name),
        files: nested.files,
        categories: nested.categories,
      };
    })
    .filter(Boolean);

  return { files, categories };
}

function generateManifest() {
  const { files, categories } = scanDirectory(TEMPLATES_DIR);

  const all = [...categories];
  if (files.length > 0) {
    all.push({
      name: "Other Documents",
      icon: "FolderOpen",
      files,
      categories: [],
    });
  }

  const js = `// AUTO-GENERATED by scripts/template-manifest-plugin.js — DO NOT EDIT.\n// Regenerated automatically from ${TEMPLATES_DIR} on every dev/build.\n\nexport const templateCategories = ${JSON.stringify(all, null, 2)};\n`;
  fs.writeFileSync(OUTPUT_FILE, js, "utf8");
  return all;
}

export default function templateManifestPlugin() {
  return {
    name: "template-manifest",
    configResolved() {
      generateManifest();
    },
    configureServer(server) {
      let timer = null;
      const regenerate = () => {
        if (timer) return;
        timer = setTimeout(() => {
          timer = null;
          try {
            const before = requireManifestCount();
            generateManifest();
            const after = requireManifestCount();
            if (JSON.stringify(before) !== JSON.stringify(after)) {
              server.ws.send({ type: "full-reload" });
            }
          } catch (err) {
            console.error("[template-manifest]", err);
          }
        }, 300);
      };

      const templatesPath = path.resolve(TEMPLATES_DIR);
      try {
        const watcher = fs.watch(templatesPath, { recursive: true }, regenerate);
        server.httpServer?.on("close", () => watcher.close());
      } catch {
        console.warn("[template-manifest] could not watch " + templatesPath);
      }
    },
  };
}

function requireManifestCount() {
  const raw = fs.readFileSync(OUTPUT_FILE, "utf8");
  const match = raw.match(/export const templateCategories = (\[.*\]);/s);
  if (!match) return null;
  return JSON.parse(match[1]);
}
